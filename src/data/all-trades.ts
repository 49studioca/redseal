function trade(
  code: string,
  slug: string,
  name: string,
  shortName: string,
  icon: string,
  description: string,
  status: Trade["status"] = "coming_soon",
  overrides: Partial<Trade> = {},
): Trade {
  const id = overrides.id ?? `trade-${slug}`;
  return {
    id,
    code,
    slug,
    name,
    short_name: shortName,
    icon,
    exam_question_count: 120,
    exam_time_minutes: 240,
    pass_percentage: 70,
    is_open_book: false,
    reference_doc_types: ["WHMIS"],
    status,
    description,
    ...overrides,
  };
}

